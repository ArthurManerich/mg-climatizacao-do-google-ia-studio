-- A estrutura JSON permanece flexível por compatibilidade com as configurações
-- atuais. Validações específicas devem ocorrer por chave antes de futuramente
-- serem promovidas a constraints sem quebrar formatos já armazenados.

CREATE TABLE IF NOT EXISTS public.admin_users (
  user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. VERIFICAÇÃO ADMINISTRATIVA
-- SECURITY DEFINER permite consultar admin_users sem expor a tabela.
-- A função não recebe parâmetros do cliente e nunca autoriza auth.uid() nulo.
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT COALESCE(
    auth.uid() IS NOT NULL
    AND EXISTS (
      SELECT 1
      FROM public.admin_users
      WHERE user_id = auth.uid()
    ),
    false
  );
$$;

REVOKE ALL ON FUNCTION public.is_admin() FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.is_admin() FROM anon;
GRANT EXECUTE ON FUNCTION public.is_admin() TO authenticated;

