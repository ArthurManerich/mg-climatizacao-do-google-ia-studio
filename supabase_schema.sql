CREATE TABLE IF NOT EXISTS public.testimonials (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  role TEXT DEFAULT 'Cliente',
  text TEXT NOT NULL,
  rating INT DEFAULT 5,
  order_index INT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Adiciona a validação somente quando os dados existentes já são compatíveis.
-- Registros antigos fora da faixa são preservados e impedem apenas a criação
-- automática da constraint, evitando uma migração destrutiva ou com falha.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'testimonials_rating_between_1_and_5'
      AND conrelid = 'public.testimonials'::regclass
  ) THEN
    IF NOT EXISTS (
      SELECT 1 FROM public.testimonials
      WHERE rating IS NOT NULL AND rating NOT BETWEEN 1 AND 5
    ) THEN
      ALTER TABLE public.testimonials
        ADD CONSTRAINT testimonials_rating_between_1_and_5
        CHECK (rating BETWEEN 1 AND 5) NOT VALID;
      ALTER TABLE public.testimonials
        VALIDATE CONSTRAINT testimonials_rating_between_1_and_5;
    ELSE
      RAISE NOTICE 'Constraint de rating não adicionada: existem valores fora da faixa de 1 a 5.';
    END IF;
  END IF;
END
$$;

CREATE TABLE IF NOT EXISTS public.portfolio (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
