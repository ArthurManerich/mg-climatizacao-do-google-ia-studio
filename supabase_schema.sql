  WITH CHECK ((SELECT public.is_admin()));

-- Usuário autenticado consulta, no máximo, a própria associação.
-- SECURITY DEFINER evita recursão ao verificar administradores já autorizados.
CREATE POLICY "Administradores leem o proprio acesso"
  ON public.admin_users FOR SELECT TO authenticated
  USING ((SELECT auth.uid()) = user_id OR (SELECT public.is_admin()));

-- Somente um administrador previamente autorizado gerencia associações.
-- Um usuário comum não consegue inserir o próprio UUID nem se autoelevar.
CREATE POLICY "Apenas administradores gerenciam admin_users"
  ON public.admin_users FOR ALL TO authenticated
  USING ((SELECT public.is_admin()))
  WITH CHECK ((SELECT public.is_admin()));

