-- 5. POLICIES DAS TABELAS PÚBLICAS
-- O site lê estes dados sem login. Toda escrita exige associação administrativa.
CREATE POLICY "Permitir leitura pública de servicos"
  ON public.services FOR SELECT TO public USING (true);
CREATE POLICY "Administradores gerenciam servicos"
  ON public.services FOR ALL TO authenticated
  USING ((SELECT public.is_admin()))
  WITH CHECK ((SELECT public.is_admin()));

CREATE POLICY "Permitir leitura pública de faq"
  ON public.faq FOR SELECT TO public USING (true);
CREATE POLICY "Administradores gerenciam faq"
  ON public.faq FOR ALL TO authenticated
  USING ((SELECT public.is_admin()))
  WITH CHECK ((SELECT public.is_admin()));

CREATE POLICY "Permitir leitura pública de depoimentos"
  ON public.testimonials FOR SELECT TO public USING (true);
CREATE POLICY "Administradores gerenciam depoimentos"
